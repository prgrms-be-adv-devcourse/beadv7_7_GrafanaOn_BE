SELECT
	CASE
		WHEN aggregate_id::bigint BETWEEN  101 AND  199 THEN '1xx 운동화'
		WHEN aggregate_id::bigint BETWEEN  201 AND  299 THEN '2xx 가방'
		WHEN aggregate_id::bigint BETWEEN  301 AND  399 THEN '3xx 시계'
		WHEN aggregate_id::bigint BETWEEN  401 AND  499 THEN '4xx 카메라'
		WHEN aggregate_id::bigint BETWEEN  501 AND  599 THEN '5xx 생활가전'
		WHEN aggregate_id::bigint BETWEEN  601 AND  699 THEN '6xx 의류'
		WHEN aggregate_id::bigint BETWEEN  701 AND  799 THEN '7xx 가구'
		WHEN aggregate_id::bigint BETWEEN  801 AND  899 THEN '8xx 악기'
		WHEN aggregate_id::bigint BETWEEN  901 AND  999 THEN '9xx 도서/취미'
		ELSE '10xx 스포츠/아웃도어'
	END AS category,
	count(DISTINCT aggregate_id) AS products
FROM recommendation_inbox
GROUP BY category
ORDER BY category;

