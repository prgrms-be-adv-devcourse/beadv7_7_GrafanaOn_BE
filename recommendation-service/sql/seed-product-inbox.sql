-- 왜 필요한가:
--   commerce-service 의 Outbox / Relay 가 아직 없어서 recommendation_inbox 에 이벤트가
--   들어오지 않는다. 임베딩 파이프라인과 유사 상품 조회를 먼저 만들어보려면
--   Relay 가 넣어줬을 법한 이벤트를 손으로 채워야 한다.
--
-- 무엇을 넣는가:
--   1) 상품 Story 100건 (PENDING)
--      카테고리별로 ID 를 묶어두었다. 같은 묶음 안의 상품이 Top-K 상위에 오면
--      추천이 납득 가능한 것이고, 묶음을 가로질러 섞이면 Threshold 를 의심하면 된다.
--
--        101~112  운동화      201~210  가방        301~310  시계
--        401~409  카메라      501~511  생활가전     601~612  의류
--        701~710  가구        801~809  악기        901~908  도서/취미
--        1001~1009 스포츠/아웃도어
--
--      경계에 걸치는 Story 를 일부러 섞어두었다. 러닝이라는 맥락은 같지만
--      카테고리가 다른 것들이다 — 104/109 러닝화, 304 러닝 워치, 608 러닝 바람막이,
--      1009 마라톤 메달. Threshold 를 정할 때 이런 것들을 어디서 자를지가 문제가 된다.
--
--      101 과 601 은 Readme 4장에서 모델을 고를 때 쓴 기준 Story 와 같은 내용이다.
--      (조던1 시카고 0.7214 / 가죽 자켓 0.6240) 그때 값과 비교할 수 있다.
--
--   2) 파이프라인 분기를 확인하는 이벤트 (E1~E5)
--
-- event_id 와 occurred_at 은 productId 에서 파생시킨다.
--   event_id    = 9000000000 + productId   (실제 Relay 이벤트와 겹치지 않는 대역)
--   occurred_at = 2026-08-24 10:00 부터 productId 순으로 1분씩
-- 고정값이라 여러 번 실행해도 ON CONFLICT 로 무시된다.
--
-- 실행:
--   docker exec -i commerce-postgres psql -U root -d dear < sql/seed-product-inbox.sql
--   psql -h localhost -U root -d dear -f sql/seed-product-inbox.sql
--
-- ⚠️ 로컬 전용. 운영 DB 에서는 실행하지 말 것.
-- ⚠️ 정리는 sql/cleanup-product-inbox.sql 로 한다.
-- ===========================================================================

